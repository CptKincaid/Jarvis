def test_the_voice_gallery_survives_a_config_that_cannot_answer(monkeypatch):
    """``_face_gallery`` read the config with no guard at all, while its
    sibling ``_face_owner`` has one. A raising config service -- or a typo in
    ``camera.face_backend``, which ``backend_for`` refuses BY DESIGN -- took
    the whole voice path down with a traceback.

    It may not guess a model either: opening the default gallery over a store
    another model wrote is how "who do you recognise" answers "nobody" over a
    live enrolment. So it returns None and the command says so."""
    from jarvis import commander as cm

    class Raises:
        def get(self, key, default=None):
            raise RuntimeError("the config service is down")

    class Typo:
        def get(self, key, default=None):
            return "insighface" if key == "camera.face_backend" else default

    class Ctx:
        def __init__(self, cfg):
            self.cfg = cfg

        def _svc(self, name):
            return self.cfg if name == "assistant" else None

    assert cm._face_gallery(Ctx(Raises())) is None
    assert cm._face_gallery(Ctx(Typo())) is None

    cmd = [c for c in cm.ASSISTANT_TIER1 if c.name == "face gallery"][0]
    text = "who do you recognise"
    out = cmd.handler(Ctx(Typo()), text, cmd.matcher(text))
    assert out.handled and out.speak
    assert "face_backend" in out.reply
